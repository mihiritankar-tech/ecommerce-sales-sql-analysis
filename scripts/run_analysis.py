"""Run every query in sql/02-06 against ecommerce.db and save the results as Markdown tables."""
import re, sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
db = sqlite3.connect(ROOT / "ecommerce.db")
out = ["# Query Results\n", "_Generated by `scripts/run_analysis.py`._\n"]

for sql_file in sorted((ROOT / "sql").glob("0[2-9]_*.sql")):
    text = sql_file.read_text()
    # split on the "-- Qn." headers so each query keeps its title
    for title, body in re.findall(r"-- (Q\d+\..*?)\n(.*?)(?=\n-- Q\d+\.|\Z)", text, re.S):
        cur = db.execute(body.strip().rstrip(";"))
        cols = [c[0] for c in cur.description]
        rows = cur.fetchall()
        out.append(f"\n## {title.strip()}\n_Source: `sql/{sql_file.name}`_\n")
        out.append("| " + " | ".join(cols) + " |")
        out.append("|" + "---|" * len(cols))
        for r in rows:
            out.append("| " + " | ".join(f"{v:,}" if isinstance(v, (int, float)) and not isinstance(v, bool) and abs(v) >= 1000 else str(v) for v in r) + " |")

(ROOT / "results").mkdir(exist_ok=True)
(ROOT / "results" / "query_results.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
